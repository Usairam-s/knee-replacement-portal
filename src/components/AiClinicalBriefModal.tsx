"use client";

import { useState } from "react";
import {
  Sparkles,
  X,
  Copy,
  Check,
  Stethoscope,
  Activity,
  AlertTriangle,
  Footprints,
  ShieldAlert,
  ShieldCheck,
  Clock,
  Printer,
} from "lucide-react";
import { toast } from "sonner";

export interface AiClinicalBriefData {
  executiveSummary: string;
  kinematicProgress: string;
  painAndEffusion: string;
  complicationAnalysis: string;
  surgeonRecommendations: string;
  physiotherapyDirectives: string;
  triageVerdict: string;
}

interface AiClinicalBriefModalProps {
  isOpen: boolean;
  onClose: () => void;
  isLoading: boolean;
  data: AiClinicalBriefData | null;
  patientName: string;
  patientId: string;
  postOpDay: number;
}

export function AiClinicalBriefModal({
  isOpen,
  onClose,
  isLoading,
  data,
  patientName,
  patientId,
  postOpDay,
}: AiClinicalBriefModalProps) {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const handleCopy = () => {
    if (!data) return;
    const text = `POSTOP-CHECK AI CLINICAL RECOVERY BRIEF
Patient: ${patientName} (MRN: ${patientId})
Timeline: Post-Op Day ${postOpDay}
Date Generated: ${new Date().toLocaleString()}

VERDICT: ${data.triageVerdict}

1. EXECUTIVE CLINICAL SUMMARY:
${data.executiveSummary}

2. KINEMATIC VELOCITY & JOINT ARTHROKINEMATICS:
${data.kinematicProgress}

3. PAIN TRAJECTORY & EFFUSION (ARTHROGENIC MUSCLE INHIBITION):
${data.painAndEffusion}

4. COMPLICATION & AAOS RED FLAG ANALYSIS:
${data.complicationAnalysis}

5. ATTENDING SURGEON RECOMMENDATIONS:
${data.surgeonRecommendations}

6. PHYSICAL THERAPIST DIRECTIVES:
${data.physiotherapyDirectives}

Generated by PostOp-Check MedTech Clinical AI Engine`;

    navigator.clipboard.writeText(text);
    setCopied(true);
    toast.success("Clinical brief copied to clipboard for EMR charting!");
    setTimeout(() => setCopied(false), 2000);
  };

  const isUrgent =
    data?.triageVerdict.includes("URGENT") ||
    data?.triageVerdict.includes("ESCALAT") ||
    data?.triageVerdict.includes("RED");

  const isWatch =
    data?.triageVerdict.includes("PLATEAU") ||
    data?.triageVerdict.includes("WATCH") ||
    data?.triageVerdict.includes("MODERATE");

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-4 bg-slate-900/60 backdrop-blur-xs animate-in fade-in duration-150">
      <div className="bg-white rounded-3xl border border-slate-200 shadow-2xl w-full max-w-3xl max-h-[90vh] flex flex-col overflow-hidden">
        {/* Modal Header */}
        <div className="px-6 py-4 border-b border-slate-100 flex items-center justify-between shrink-0 bg-slate-50/80">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-xl bg-gradient-to-tr from-teal-600 to-indigo-600 flex items-center justify-center text-white shadow-xs">
              <Sparkles className="w-4 h-4 text-amber-200" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="text-sm font-bold text-slate-900 tracking-tight">
                  AI Clinical Recovery Brief
                </h3>
                <span className="text-[10px] font-bold px-2 py-0.5 rounded-full bg-indigo-50 text-indigo-700 border border-indigo-200">
                  GPT-4o Clinical Intelligence
                </span>
              </div>
              <p className="text-[11px] text-slate-500">
                Patient: <strong className="text-slate-700">{patientName}</strong> &bull; Day {postOpDay} Longitudinal Audit
              </p>
            </div>
          </div>

          <button
            onClick={onClose}
            className="w-8 h-8 rounded-full hover:bg-slate-200 flex items-center justify-center text-slate-400 hover:text-slate-700 transition-colors"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        {/* Modal Body */}
        <div className="p-6 overflow-y-auto space-y-4 text-xs">
          {isLoading ? (
            <div className="py-16 text-center space-y-3">
              <div className="w-10 h-10 border-3 border-teal-600 border-t-transparent rounded-full animate-spin mx-auto" />
              <div className="space-y-1">
                <p className="text-sm font-bold text-slate-800">
                  Synthesizing Longitudinal PROMs &amp; Kinematic Trajectory...
                </p>
                <p className="text-xs text-slate-500 max-w-sm mx-auto">
                  Applying AAOS clinical guidelines, flexion velocity tracking, and effusion AMI analysis.
                </p>
              </div>
            </div>
          ) : data ? (
            <>
              {/* Triage Verdict Banner */}
              <div
                className={`p-3.5 rounded-2xl border flex items-center justify-between gap-3 ${
                  isUrgent
                    ? "bg-red-50/80 border-red-200 text-red-950"
                    : isWatch
                    ? "bg-amber-50/80 border-amber-200 text-amber-950"
                    : "bg-emerald-50/80 border-emerald-200 text-emerald-950"
                }`}
              >
                <div className="flex items-center gap-2.5">
                  {isUrgent ? (
                    <ShieldAlert className="w-5 h-5 text-red-600 shrink-0" />
                  ) : isWatch ? (
                    <Clock className="w-5 h-5 text-amber-600 shrink-0" />
                  ) : (
                    <ShieldCheck className="w-5 h-5 text-emerald-600 shrink-0" />
                  )}
                  <div>
                    <span className="text-[10px] font-bold uppercase tracking-wider block opacity-75">
                      Clinical Triage Verdict
                    </span>
                    <span className="text-sm font-extrabold tracking-tight">
                      {data.triageVerdict}
                    </span>
                  </div>
                </div>

                <button
                  onClick={handleCopy}
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-[11px] font-bold bg-white border border-current shadow-2xs hover:bg-slate-50 transition-colors"
                >
                  {copied ? (
                    <>
                      <Check className="w-3.5 h-3.5 text-teal-600" />
                      <span>Copied!</span>
                    </>
                  ) : (
                    <>
                      <Copy className="w-3.5 h-3.5" />
                      <span>Copy EMR Note</span>
                    </>
                  )}
                </button>
              </div>

              {/* Executive Summary */}
              <div className="p-4 rounded-2xl bg-slate-50 border border-slate-200/80 space-y-1.5">
                <span className="text-[10px] font-bold uppercase tracking-wider text-slate-400 flex items-center gap-1.5">
                  <Stethoscope className="w-3.5 h-3.5 text-teal-600" />
                  <span>1. Executive Clinical Synthesis</span>
                </span>
                <p className="text-xs text-slate-800 leading-relaxed font-medium">
                  {data.executiveSummary}
                </p>
              </div>

              {/* 2-Column Clinical Sections */}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-3.5">
                {/* Kinematics */}
                <div className="p-4 rounded-2xl bg-white border border-slate-200 space-y-1.5 shadow-2xs">
                  <span className="text-[10px] font-bold uppercase tracking-wider text-teal-700 flex items-center gap-1.5">
                    <Activity className="w-3.5 h-3.5" />
                    <span>2. Kinematic Velocity &amp; AROM</span>
                  </span>
                  <p className="text-xs text-slate-600 leading-relaxed">
                    {data.kinematicProgress}
                  </p>
                </div>

                {/* Pain & Effusion */}
                <div className="p-4 rounded-2xl bg-white border border-slate-200 space-y-1.5 shadow-2xs">
                  <span className="text-[10px] font-bold uppercase tracking-wider text-blue-700 flex items-center gap-1.5">
                    <Footprints className="w-3.5 h-3.5" />
                    <span>3. NPRS Pain &amp; Effusion AMI</span>
                  </span>
                  <p className="text-xs text-slate-600 leading-relaxed">
                    {data.painAndEffusion}
                  </p>
                </div>

                {/* Complications */}
                <div className="p-4 rounded-2xl bg-white border border-slate-200 space-y-1.5 shadow-2xs md:col-span-2">
                  <span className="text-[10px] font-bold uppercase tracking-wider text-red-700 flex items-center gap-1.5">
                    <AlertTriangle className="w-3.5 h-3.5" />
                    <span>4. Complication &amp; AAOS Red Flag Analysis</span>
                  </span>
                  <p className="text-xs text-slate-600 leading-relaxed">
                    {data.complicationAnalysis}
                  </p>
                </div>
              </div>

              {/* Multidisciplinary Action Directives */}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-3.5 pt-1">
                <div className="p-4 rounded-2xl bg-teal-50/60 border border-teal-200 space-y-1.5">
                  <span className="text-[10px] font-bold uppercase tracking-wider text-teal-900 block">
                    👨‍⚕️ Attending Surgeon Directives:
                  </span>
                  <p className="text-xs text-teal-950/90 leading-relaxed">
                    {data.surgeonRecommendations}
                  </p>
                </div>

                <div className="p-4 rounded-2xl bg-indigo-50/60 border border-indigo-200 space-y-1.5">
                  <span className="text-[10px] font-bold uppercase tracking-wider text-indigo-900 block">
                    🏃 Physical Therapist Directives:
                  </span>
                  <p className="text-xs text-indigo-950/90 leading-relaxed">
                    {data.physiotherapyDirectives}
                  </p>
                </div>
              </div>
            </>
          ) : (
            <div className="py-12 text-center text-slate-500">
              No brief data available.
            </div>
          )}
        </div>

        {/* Modal Footer */}
        <div className="px-6 py-3 border-t border-slate-100 flex items-center justify-between shrink-0 bg-slate-50/50">
          <span className="text-[11px] text-slate-400">
            Confidential medical decision support for verified clinical team only.
          </span>
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-xl text-xs font-bold text-slate-700 bg-slate-100 hover:bg-slate-200 transition-colors"
          >
            Close Brief
          </button>
        </div>
      </div>
    </div>
  );
}
